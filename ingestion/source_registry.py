def seed_source_registry(db: Database) -> int:
    """Write catalog entries into the database."""
    now = datetime.now(timezone.utc).isoformat()
    for entry in SOURCE_CATALOG:
        entry.last_checked = now
        db.upsert_source(entry)
    return len(SOURCE_CATALOG)


def update_download_status(
    db: Database, source_id: str, status: DownloadStatus, notes: str | None = None
) -> None:
    sources = {s["source_id"]: s for s in db.list_sources()}
    if source_id not in sources:
        return
    row = sources[source_id]
    entry = SourceRegistryEntry(
        source_id=row["source_id"],
        name=row["name"],
        url=row["url"],
        civilisation=row["civilisation"],
        format=row["format"],
        licence=row["licence"],
        redistribution_ok=bool(row["redistribution_ok"]),
        api_limitations=row["api_limitations"],
        availability=row["availability"],
        download_status=status,
        data_quality=row["data_quality"],
        notes=notes if notes is not None else (row["notes"] or ""),
        last_checked=datetime.now(timezone.utc).isoformat(),
    )
    db.upsert_source(entry)
